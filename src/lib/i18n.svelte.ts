export type Lang = "pt" | "en";

const saved = localStorage.getItem("lang");
export const EMU_NAME: Record<Emu, string> = { eden: "Eden", yuzu: "yuzu", ryujinx: "Ryujinx" };
const ua = navigator.userAgent;
// Caminho padrão de cada emulador por sistema (Ryujinx fica em config; Eden/yuzu em data).
const [DATA, CFG] = ua.includes("Windows")
  ? ["%APPDATA%\\", "%APPDATA%\\"]
  : ua.includes("Mac")
    ? ["~/Library/Application Support/", "~/Library/Application Support/"]
    : ["~/.local/share/", "~/.config/"];
export const EMU_HINT: Record<Emu, string> = {
  eden: `${DATA}eden`,
  yuzu: `${DATA}yuzu`,
  ryujinx: `${CFG}Ryujinx`,
};
export const i18n = $state<{ lang: Lang; emu: string }>({
  lang: saved === "pt" || saved === "en" ? saved : navigator.language.toLowerCase().startsWith("pt") ? "pt" : "en",
  emu: EMU_NAME.eden,
});
export const locale = () => (i18n.lang === "pt" ? "pt-BR" : "en");
export function setLang(l: Lang) {
  i18n.lang = l;
  localStorage.setItem("lang", l);
  document.documentElement.lang = locale();
}

