export function t(key: keyof typeof dict.pt, vars: Record<string, string | number> = {}): string {
  const all = { emu: i18n.emu, ...vars };
  return dict[i18n.lang][key].replace(/\{(\w+)\}/g, (_, k) => String(all[k as keyof typeof all] ?? ""));
}

